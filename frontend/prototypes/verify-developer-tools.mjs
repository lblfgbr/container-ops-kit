  assert.equal(find('.dt-config-bar .dt-tag-picker summary small').textContent,'Tag');
  assert.ok(find('.dt-advanced-picker #ct-feature'),'Original feature filter remains under advanced options');
  await click('[data-bin-mode="batch"]');await click('[data-bin-sample]');
  assert.match(find('.ct-input-label').textContent,/每行一条/,'Keep batch input guidance');
  const sample=find('#ct-bin-input').value.split('\n').find(line=>line.trim()&&!line.startsWith('#'));
  await fill('#ct-bin-input',sample+'\nnot-hex');
  find('#ct-bin-input').dispatchEvent(new w.KeyboardEvent('keydown',{key:'Enter',metaKey:true,bubbles:true}));await wait();
  assert.match(find('.dt-output-pane>.ct-command-title').textContent,/成功 1.*失败 1/);
